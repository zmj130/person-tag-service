-- 达梦 8 初始化脚本。建议使用独立模式/用户执行，不要直接在业务共享模式中运行。

CREATE TABLE PT_TAG_DEFINITION (
    ID VARCHAR(32) NOT NULL,
    CODE VARCHAR(64) NOT NULL,
    NAME VARCHAR(100) NOT NULL,
    CATEGORY VARCHAR(100) NOT NULL,
    DESCRIPTION VARCHAR(500),
    STATUS INT DEFAULT 1 NOT NULL,
    AUTO_APPROVE INT DEFAULT 0 NOT NULL,
    CREATED_AT TIMESTAMP NOT NULL,
    UPDATED_AT TIMESTAMP NOT NULL,
    CONSTRAINT PK_PT_TAG_DEFINITION PRIMARY KEY (ID),
    CONSTRAINT UK_PT_TAG_DEFINITION_CODE UNIQUE (CODE)
);

COMMENT ON TABLE PT_TAG_DEFINITION IS '标签定义表';
COMMENT ON COLUMN PT_TAG_DEFINITION.ID IS '标签主键，32位UUID';
COMMENT ON COLUMN PT_TAG_DEFINITION.CODE IS '标签业务编码，对接外部系统且全局唯一';
COMMENT ON COLUMN PT_TAG_DEFINITION.NAME IS '标签名称';
COMMENT ON COLUMN PT_TAG_DEFINITION.CATEGORY IS '标签分类';
COMMENT ON COLUMN PT_TAG_DEFINITION.DESCRIPTION IS '标签说明';
COMMENT ON COLUMN PT_TAG_DEFINITION.STATUS IS '启用状态：1启用，0停用';
COMMENT ON COLUMN PT_TAG_DEFINITION.AUTO_APPROVE IS '规则命中后是否自动通过：1是，0否';
COMMENT ON COLUMN PT_TAG_DEFINITION.CREATED_AT IS '创建时间';
COMMENT ON COLUMN PT_TAG_DEFINITION.UPDATED_AT IS '更新时间';

CREATE TABLE PT_TAG_RULE (
    ID VARCHAR(32) NOT NULL,
    TAG_ID VARCHAR(32) NOT NULL,
    KEYWORD VARCHAR(200) NOT NULL,
    NORMALIZED_KEYWORD VARCHAR(200) NOT NULL,
    STATUS INT DEFAULT 1 NOT NULL,
    VERSION_NO INT DEFAULT 1 NOT NULL,
    CREATED_AT TIMESTAMP NOT NULL,
    UPDATED_AT TIMESTAMP NOT NULL,
    CONSTRAINT PK_PT_TAG_RULE PRIMARY KEY (ID),
    CONSTRAINT FK_PT_TAG_RULE_TAG FOREIGN KEY (TAG_ID) REFERENCES PT_TAG_DEFINITION(ID),
    CONSTRAINT UK_PT_TAG_RULE_WORD UNIQUE (TAG_ID, NORMALIZED_KEYWORD)
);

COMMENT ON TABLE PT_TAG_RULE IS '标签关键词规则表';
COMMENT ON COLUMN PT_TAG_RULE.ID IS '规则主键，32位UUID';
COMMENT ON COLUMN PT_TAG_RULE.TAG_ID IS '关联标签主键';
COMMENT ON COLUMN PT_TAG_RULE.KEYWORD IS '原始匹配关键词';
COMMENT ON COLUMN PT_TAG_RULE.NORMALIZED_KEYWORD IS '标准化后的匹配关键词';
COMMENT ON COLUMN PT_TAG_RULE.STATUS IS '启用状态：1启用，0停用';
COMMENT ON COLUMN PT_TAG_RULE.VERSION_NO IS '规则版本号，每次状态变更递增';
COMMENT ON COLUMN PT_TAG_RULE.CREATED_AT IS '创建时间';
COMMENT ON COLUMN PT_TAG_RULE.UPDATED_AT IS '更新时间';

CREATE TABLE PT_PERSON (
    ID VARCHAR(32) NOT NULL,
    EXTERNAL_ID VARCHAR(100) NOT NULL,
    NAME VARCHAR(100) NOT NULL,
    GENDER VARCHAR(20),
    ORGANIZATION VARCHAR(200),
    OCCUPATION VARCHAR(200),
    ADDRESS VARCHAR(500),
    REMARK VARCHAR(1000),
    SOURCE_UPDATED_AT TIMESTAMP,
    DELETED_FLAG INT DEFAULT 0 NOT NULL,
